<#
.SYNOPSIS
    Populates the "Publication Registry" SharePoint List with verified baseline seed data.

.DESCRIPTION
    Loads the JSON seed file generated by scripts/export_sharepoint_seed.py and
    batch-inserts or updates list items using PnP.PowerShell batching.

.PARAMETER SiteUrl
    The absolute URL of the SharePoint Site or OneDrive.

.PARAMETER SeedJsonPath
    Path to the seed JSON file (default: private/ops/sharepoint-seed/publication-registry-seed.json).

.EXAMPLE
    .\Import-SharePointSeed.ps1 -SiteUrl "https://example.sharepoint.com/sites/Research"
#>

[CmdletBinding()]
param(
    [string]$SiteUrl = $env:SHAREPOINT_SITE_URL,
    [string]$SeedJsonPath = "$PSScriptRoot/../private/ops/sharepoint-seed/publication-registry-seed.json",
    [switch]$DeviceLogin
)

$ErrorActionPreference = "Stop"

if ([string]::IsNullOrWhiteSpace($SiteUrl)) { throw "-SiteUrl or SHAREPOINT_SITE_URL is required; no tenant default is embedded." }

if (-not (Test-Path $SeedJsonPath)) {
    Write-Error "Seed JSON file not found at: $SeedJsonPath. Run 'python3 scripts/export_sharepoint_seed.py' first."
}

Write-Host "=== CHHHS Publication Registry: Baseline Seed Import ===" -ForegroundColor Cyan
Write-Host "Target Site: $SiteUrl"
Write-Host "Seed Source: $SeedJsonPath"

Import-Module PnP.PowerShell -ErrorAction SilentlyContinue

if ($DeviceLogin) {
    Write-Host "Connecting using Device Login..." -ForegroundColor Yellow
    Connect-PnPOnline -Url $SiteUrl -DeviceLogin -ClientId '{{SHAREPOINT_CLIENT_ID}}'
} else {
    Write-Host "Connecting using Interactive Browser..." -ForegroundColor Yellow
    Connect-PnPOnline -Url $SiteUrl -Interactive -ClientId '{{SHAREPOINT_CLIENT_ID}}'
}

$ListName = "Publication Registry"
$seedData = Get-Content -Raw -Path $SeedJsonPath | ConvertFrom-Json

Write-Host "Loaded $($seedData.Count) records to import." -ForegroundColor Green

# Batching loop
$batchSize = 50
$total = $seedData.Count
$processed = 0

for ($i = 0; $i -lt $total; $i += $batchSize) {
    $batch = New-PnPBatch
    $end = [Math]::Min($i + $batchSize, $total)
    
    for ($j = $i; $j -lt $end; $j++) {
        $item = $seedData[$j]
        
        $values = @{
            "Title" = [string]$item.Title
            "SourceKey" = [string]$item.SourceKey
            "CanonicalKey" = [string]$item.CanonicalKey
            "Authors" = [string]$item.Authors
            "Journal" = [string]$item.Journal
            "PublicationMonth" = [string]$item.PublicationMonth
            "PublicationDateRaw" = [string]$item.PublicationDateRaw
            "PublicationDatePrecision" = [string]$item.PublicationDatePrecision
            "SourceSet" = [string]$item.SourceSet
            "PMID" = [string]$item.PMID
            "DOI" = [string]$item.DOI
            "MatchedFacilities" = [string]$item.MatchedFacilities
            "CHHHSAffiliatedAuthors" = [string]$item.CHHHSAffiliatedAuthors
            "AttributionEvidence" = [string]$item.AttributionEvidence
            "ReviewStatus" = [string]$item.ReviewStatus
            "ReviewNotes" = [string]$item.ReviewNotes
        }

        if ($item.PublicationYear) {
            $values["PublicationYear"] = [int]$item.PublicationYear
        }
        if ($item.PubMedURL) {
            $values["PubMedURL"] = [string]$item.PubMedURL
        }
        if ($item.DORAURL) {
            $values["DORAURL"] = [string]$item.DORAURL
        }
        if ($item.FirstObservedUTC) {
            $values["FirstObservedUTC"] = [DateTime]$item.FirstObservedUTC
        }
        if ($item.LastObservedUTC) {
            $values["LastObservedUTC"] = [DateTime]$item.LastObservedUTC
        }

        Add-PnPListItem -List $ListName -Values $values -Batch $batch | Out-Null
    }

    Invoke-PnPBatch -Batch $batch
    $processed = $end
    Write-Host "Progress: $processed / $total items imported ($([Math]::Round(($processed/$total)*100, 1))%)..." -ForegroundColor Cyan
}

Write-Host "Seed import completed successfully! $total items processed." -ForegroundColor Green
